print()

values = []

print("Please enter values, Q to quit:")

user_input = input()

while user_input.upper() != "Q":
    value = float(user_input)
    values.append(value)
    user_input = input()

print()
print("Here are the results:")

largest = max(values)
smallest = min(values)

for value in values:
    print(value, end="")

    if value == largest:
        print(" <== largest value")
    elif value == smallest:
        print(" <== smallest value")
    else:
        print()
